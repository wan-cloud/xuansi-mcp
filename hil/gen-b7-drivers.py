#!/usr/bin/env python3
"""gen-b7-drivers — mechanically extract the b7 loopback driver sources
(I2CECHO_LUA / SPILOOP_LUA) from the fw repo's tools/b7-drivers.py via AST
literal dump and emit hil/b7-drivers.go with the byte-exact constants plus
the expected sha256s from the controller ruling. Also derives
i2cecho@1.1.0 from the extracted 1.0.0 source by the MINIMAL diff (adds
one `drv.version = "1.1.0"` line inside attach; first line stays --@api 1).

Nothing is retyped by hand: if the fw file drifts, the sha assertions
below (and the HIL's own startup assert) fail loudly.
"""
import ast
import hashlib
import sys
from pathlib import Path

FW = Path("/home/wan/work/Project/xuansi-hardware-probe/"
          "code/xuansi-fw/tools/b7-drivers.py")
OUT = Path(__file__).resolve().parent.parent / "hil" / "b7-drivers.go"

# The controller ruling text carried a 63-char i2cecho sha (one dropped
# "a"); the fw repo's own T3/T4 evidence logs (2026-11-05-b7-t3/t4) and
# the live file agree on the full 64-char digest below — same bytes (1412).
EXPECT_I2C = ("a9c83d9499224196ecc1bcf6d3d79125bc13b313727ac4224fcfdb08"
              "ef0d97d4")
EXPECT_SPI = ("047f3757d01faa1acacf6449a34ca5499f0dd6acbfccbd217bf5e7c"
              "40bc55458")
EXPECT_I2C_BYTES = 1412
EXPECT_SPI_BYTES = 1398


def extract(name):
    tree = ast.parse(FW.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == name:
                    return ast.literal_eval(node.value)
    raise SystemExit(f"constant {name} not found in {FW}")


def go_quote(s: str) -> str:
    """One Go interpreted-string literal, byte-exact for UTF-8 content."""
    out = ['"']
    for b in s.encode("utf-8"):
        if b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        elif b == 0x0A:
            out.append("\\n")
        elif b == 0x09:
            out.append("\\t")
        elif b == 0x0D:
            out.append("\\r")
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append(f"\\x{b:02x}")
    out.append('"')
    return "".join(out)


def main():
    i2c = extract("I2CECHO_LUA")
    spi = extract("SPILOOP_LUA")
    for name, src, sha, n in (("I2CECHO_LUA", i2c, EXPECT_I2C, EXPECT_I2C_BYTES),
                              ("SPILOOP_LUA", spi, EXPECT_SPI, EXPECT_SPI_BYTES)):
        got = hashlib.sha256(src.encode()).hexdigest()
        if got != sha or len(src.encode()) != n:
            raise SystemExit(
                f"{name}: sha/size drift vs the controller ruling "
                f"(sha={got} bytes={len(src.encode())}; want {sha}/{n})")
        if src.splitlines()[0] != "--@api 1":
            raise SystemExit(f"{name}: first line gate drifted")
    # i2cecho@1.1.0 — minimal diff: one drv.version line right after the
    # `local drv = {}` inside attach. First line stays --@api 1.
    marker = "  local drv = {}\n"
    if i2c.count(marker) != 1:
        raise SystemExit("i2cecho 1.1.0 derivation marker not unique")
    i2c11 = i2c.replace(marker, marker + '  drv.version = "1.1.0"\n', 1)
    sha11 = hashlib.sha256(i2c11.encode()).hexdigest()
    if i2c11.splitlines()[0] != "--@api 1":
        raise SystemExit("i2cecho 1.1.0 first line gate drifted")

    OUT.write_text(
        "// Code generated by hil/gen-b7-drivers.py from the fw repo's\n"
        "// tools/b7-drivers.py (AST literal dump — NEVER retyped by hand).\n"
        "// Source: xuansi-fw@bfa8e04 tools/b7-drivers.py I2CECHO_LUA +\n"
        "// SPILOOP_LUA. Byte-exact; the sha256s are the controller-ruled\n"
        "// constants and b7-mcp.go asserts them at startup.\n"
        "package main\n\n"
        "const b7I2CEchoV100 = " + go_quote(i2c) + "\n\n"
        "const b7SPILoopV100 = " + go_quote(spi) + "\n\n"
        "// b7I2CEchoV110 = 1.0.0 + the single `drv.version = \"1.1.0\"` line\n"
        "// (the S7 version-swap body); its sha256 is computed at runtime —\n"
        "// the hot-swap assertions key on BEHAVIOR (drv.version), not a\n"
        "// hand-computed constant.\n"
        "const b7I2CEchoV110 = " + go_quote(i2c11) + "\n\n"
        "const b7I2CEchoV100SHA256 = \"" + EXPECT_I2C + "\"\n\n"
        "const b7SPILoopV100SHA256 = \"" + EXPECT_SPI + "\"\n\n"
        "// b7I2CEchoV110SHA256 is the derived 1.1.0 digest for the\n"
        "// transcript (computed by the generator, re-asserted at runtime\n"
        "// against the actual constant):\n"
        "const b7I2CEchoV110SHA256 = \"" + sha11 + "\"\n",
        encoding="utf-8")
    print(f"i2cecho@1.0.0  bytes={len(i2c.encode())} sha256={EXPECT_I2C}")
    print(f"spiloop@1.0.0  bytes={len(spi.encode())} sha256={EXPECT_SPI}")
    print(f"i2cecho@1.1.0  bytes={len(i2c11.encode())} sha256={sha11}")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    sys.exit(main())
